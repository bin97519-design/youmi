// Explicit group execution uses the existing task store; this module never calls a provider API.
const BUSY = new Set(['preparing', 'submitting', 'queued', 'running', 'paused', 'uncertain'])
const own = (value) => JSON.parse(JSON.stringify(value))
const stableValue = (value) => {
  if (Array.isArray(value)) return value.map(stableValue)
  if (value && typeof value === 'object')
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((key) => [key, stableValue(value[key])]),
    )
  return value
}
const stableStringify = (value) => JSON.stringify(stableValue(value))
const media = (node) => ['image', 'video', 'audio'].includes(node?.data?.kind)
const title = (node) => node?.data?.title || node?.id || '节点'
const pending = (node) =>
  BUSY.has(node?.data?.runState) ||
  Boolean(
    node?.data?.generation?.queryPending ||
    node?.data?.generation?.persistPending ||
    node?.data?.generation?.unresolvedTaskIds?.length,
  )
const inputSignature = (node) =>
  stableStringify([
    node?.data?.kind,
    node?.data?.model,
    node?.data?.mode,
    node?.data?.prompt,
    node?.data?.params,
    node?.data?.switches,
    node?.data?.editTemplate,
    node?.data?.stylePreset,
    node?.data?.sourceImageNodeId,
  ])
const edgeSignature = (edges, memberIds) =>
  JSON.stringify(
    edges
      .filter((edge) => memberIds.has(edge.target))
      .map((edge) => [edge.source, edge.target, edge.sourceHandle, edge.targetHandle])
      .sort((left, right) => JSON.stringify(left).localeCompare(JSON.stringify(right))),
  )

function abortError() {
  const error = new Error('已停止整组执行，已提交的任务会继续按原任务查询，不会重复提交')
  error.name = 'AbortError'
  return error
}
function throwIfAborted(signal) {
  if (signal?.aborted) throw abortError()
}
function wait(delay, signal) {
  return new Promise((resolve, reject) => {
    throwIfAborted(signal)
    const timer = setTimeout(finish, delay)
    const abort = () => {
      clearTimeout(timer)
      signal?.removeEventListener('abort', abort)
      reject(abortError())
    }
    function finish() {
      signal?.removeEventListener('abort', abort)
      resolve()
    }
    signal?.addEventListener('abort', abort, { once: true })
  })
}

/** Read-only preflight. Existing media is reference material, never regenerated by a group click. */
export function groupExecutionPlan(nodes, edges, groupId) {
  if (!Array.isArray(nodes) || !Array.isArray(edges) || typeof groupId !== 'string' || !groupId)
    throw new Error('请选择一个完整分组')
  const members = nodes.filter((node) => node?.data?.groupId === groupId)
  if (members.length < 2 || members.length > 100) throw new Error('分组需包含 2～100 个节点')
  if (new Set(members.map((node) => node.id)).size !== members.length)
    throw new Error('分组节点标识重复')
  if (members.some(pending)) throw new Error('分组内存在进行中或待确认任务，请等待或继续查询原任务')
  const skipped = []
  const runnable = members.filter((node) => {
    let reason = ''
    if (!['image', 'video'].includes(node.data.kind)) reason = '此类型不支持生成'
    else if (node.data.assetUrl) reason = '已有素材，仅作为参考'
    else if (!node.data.prompt?.trim() && !node.data.editTemplate?.id) reason = '未填写生成提示词'
    if (reason) skipped.push({ id: node.id, title: title(node), reason })
    return !reason
  })
  const runnableIds = new Set(runnable.map((node) => node.id))
  const lookup = new Map(nodes.map((node) => [node.id, node]))
  const dependencies = new Map(runnable.map((node) => [node.id, new Set()]))
  for (const node of runnable) {
    const sourceIds = new Set(
      edges.filter((edge) => edge.target === node.id).map((edge) => edge.source),
    )
    const sourceImageId = node.data.sourceImageNodeId || node.data.editTemplate?.sourceNodeId
    if (sourceImageId) sourceIds.add(sourceImageId)
    for (const sourceId of sourceIds) {
      const source = lookup.get(sourceId)
      if (!source) throw new Error(`「${title(node)}」的参考节点已移除`)
      if (sourceId === node.id) throw new Error('分组内存在循环引用，请先调整连线')
      if (runnableIds.has(sourceId)) dependencies.get(node.id).add(sourceId)
      else if (pending(source)) throw new Error(`参考「${title(source)}」仍在生成或等待确认`)
      else if (media(source) && !source.data.assetUrl)
        throw new Error(`参考「${title(source)}」尚无可用素材，请先生成或移除连线`)
      else if (!media(source) && !source.data.prompt?.trim())
        throw new Error(`参考「${title(source)}」没有可用文本`)
    }
  }
  const order = []
  const remaining = new Set(runnableIds)
  while (remaining.size) {
    const ready = runnable.filter(
      (node) =>
        remaining.has(node.id) && [...dependencies.get(node.id)].every((id) => !remaining.has(id)),
    )
    if (!ready.length) throw new Error('分组内存在循环引用，请先调整连线')
    for (const node of ready) {
      order.push(node.id)
      remaining.delete(node.id)
    }
  }
  return own({
    groupId,
    name: members[0].data.groupName || '分组',
    memberIds: members.map((node) => node.id),
    order,
    skipped,
    generationCount: order.length,
  })
}

/** Bind a visible execution approval to exact inputs, not UI status, position or dimensions. */
export function groupExecutionApprovalSignature(nodes, edges, groupId) {
  const plan = groupExecutionPlan(nodes, edges, groupId)
  const ids = new Set(plan.memberIds)
  const members = nodes.filter((node) => ids.has(node.id)).sort((a, b) => a.id.localeCompare(b.id))
  const referenceIds = new Set(
    edges.filter((edge) => ids.has(edge.target)).map((edge) => edge.source),
  )
  for (const node of members) {
    const sourceId = node.data.sourceImageNodeId || node.data.editTemplate?.sourceNodeId
    if (sourceId) referenceIds.add(sourceId)
  }
  const nodeApproval = (node) => ({
    id: node.id,
    input: JSON.parse(inputSignature(node)),
    assetUrl: node.data.assetUrl || '',
  })
  return stableStringify({
    version: 1,
    groupId,
    members: members.map(nodeApproval),
    incoming: JSON.parse(edgeSignature(edges, ids)),
    references: nodes
      .filter((node) => referenceIds.has(node.id) && !ids.has(node.id))
      .sort((a, b) => a.id.localeCompare(b.id))
      .map(nodeApproval),
    order: plan.order,
  })
}

/** Caller must show/confirm this plan before invoking run; no generation occurs on construction. */
export function createGroupExecutionRunner({
  getNodes,
  getEdges,
  getScope,
  runImage,
  runVideo,
  onProgress = () => {},
  waitForResult,
  pollMs = 500,
  timeoutMs = 60 * 60 * 1000,
}) {
  let busy = false
  const scopeKey = () => JSON.stringify(getScope())
  async function run(groupId, { signal, onTarget } = {}) {
    if (busy) throw new Error('整组执行仍在处理中，请勿重复点击')
    throwIfAborted(signal)
    const scope = scopeKey()
    const plan = groupExecutionPlan(getNodes(), getEdges(), groupId)
    const members = getNodes().filter((node) => plan.memberIds.includes(node.id))
    const memberIds = new Set(plan.memberIds)
    const signatures = new Map(members.map((node) => [node.id, inputSignature(node)]))
    const skippedAssets = new Map(
      members
        .filter((node) => !plan.order.includes(node.id))
        .map((node) => [node.id, node.data.assetUrl]),
    )
    const incoming = edgeSignature(getEdges(), memberIds)
    const referenceIds = new Set(
      getEdges()
        .filter((edge) => memberIds.has(edge.target))
        .map((edge) => edge.source),
    )
    for (const node of members) {
      const sourceId = node.data.sourceImageNodeId || node.data.editTemplate?.sourceNodeId
      if (sourceId) referenceIds.add(sourceId)
    }
    const externalSources = new Map(
      [...referenceIds]
        .filter((id) => !memberIds.has(id))
        .map((id) => {
          const source = getNodes().find((node) => node.id === id)
          return [id, JSON.stringify([source?.data?.assetUrl, inputSignature(source)])]
        }),
    )
    const complete = []
    const startedIds = new Set()
    const current = () => {
      throwIfAborted(signal)
      if (scope !== scopeKey()) throw new Error('画布或账号已切换，已停止后续生成')
      const latest = getNodes()
      const liveMembers = latest.filter((node) => node.data?.groupId === groupId)
      if (
        liveMembers.length !== members.length ||
        !members.every((node) => liveMembers.includes(node)) ||
        incoming !== edgeSignature(getEdges(), memberIds) ||
        members.some(
          (node) => !startedIds.has(node.id) && inputSignature(node) !== signatures.get(node.id),
        ) ||
        [...skippedAssets].some(
          ([id, url]) => latest.find((node) => node.id === id)?.data.assetUrl !== url,
        ) ||
        [...externalSources].some(([id, signature]) => {
          const node = latest.find((item) => item.id === id)
          return signature !== JSON.stringify([node?.data?.assetUrl, inputSignature(node)])
        })
      )
        throw new Error('分组内容或输入已改变，已停止后续生成，请重新确认整组执行')
    }
    busy = true
    try {
      for (const nodeId of plan.order) {
        current()
        const node = getNodes().find((item) => item.id === nodeId)
        if (node.data.assetUrl || pending(node))
          throw new Error(`「${title(node)}」状态已改变，已停止后续生成`)
        startedIds.add(nodeId)
        onProgress({
          phase: 'submitting',
          nodeId,
          completed: complete.length,
          total: plan.order.length,
        })
        await (node.data.kind === 'image' ? runImage(nodeId, onTarget) : runVideo(nodeId, onTarget))
        current()
        if (waitForResult) await waitForResult(nodeId, { signal, current })
        else {
          const started = Date.now()
          while (true) {
            current()
            const latest = getNodes().find((item) => item.id === nodeId)
            if (latest.data.runState === 'succeeded' && latest.data.assetUrl && !pending(latest))
              break
            if (
              !['preparing', 'submitting', 'queued', 'running'].includes(latest.data.runState) &&
              !(latest.data.runState === 'succeeded' && pending(latest))
            )
              throw new Error(
                `「${title(latest)}」未完成：${latest.data.error || latest.data.statusText || '请检查节点状态'}`,
              )
            if (Date.now() - started >= timeoutMs)
              throw new Error('等待生成结果超时，已停止后续生成；请继续查询原任务，避免重复扣费')
            await wait(pollMs, signal)
          }
        }
        current()
        const result = getNodes().find((item) => item.id === nodeId)
        if (result.data.runState !== 'succeeded' || !result.data.assetUrl || pending(result))
          throw new Error(`「${title(result)}」尚无成功结果，未执行下游节点`)
        complete.push(nodeId)
        onProgress({
          phase: 'completed',
          nodeId,
          completed: complete.length,
          total: plan.order.length,
        })
      }
      return {
        plan,
        completedIds: [...complete],
        completedCount: complete.length,
        startedIds: [...startedIds],
      }
    } catch (error) {
      error.completedIds = [...complete]
      error.completedCount = complete.length
      error.startedIds = [...startedIds]
      throw error
    } finally {
      busy = false
    }
  }
  return {
    run,
    get busy() {
      return busy
    },
  }
}
